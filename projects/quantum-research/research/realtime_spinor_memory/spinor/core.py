# -*- coding: utf-8 -*-
"""core.py — спинорная фазовая машина без долговременной памяти.

Модель. Единственное состояние машины — фаза φ единичного спинора,
живущая на окружности S¹. Один шаг реального времени поворачивает фазу
на фиксированный угол θ (модельный спинорный параметр):

    φ_{t+1} = (φ_t + θ) mod 2π.

Считывание — максимального правдоподобия к ближайшей точке решётки
состояний G_θ = {0, θ, 2θ, …, (N−1)θ}, N = 2π/θ. Для модельных фаз
θ = π/k решётка замыкается ровно через N = 2k шагов (теорема TS1).

Свойства по построению:
  • память — ровно ОДИН численный регистр (φ); константы θ и N — это
    спецификация модели, а не состояние;
  • шаг — O(1) по времени и памяти при любом t (нет истории);
  • сброс стирает всё: после reset() никакая функция пост-состояния не
    восстанавливает пре-состояние лучше уровня случайности (TS2);
  • хранение истории = 0 байт: машина ничего не записывает.

Три модельные фазы исследования: θ = π/2 (S1, N=4), θ = π/3 (S2, N=6),
θ = π/7 (S3, N=14).
"""
import math

__all__ = ["MODELS", "SpinorMachine", "state_footprint"]

TAU = 2.0 * math.pi

#: модельные фазы исследования: имя → (θ, k)
MODELS = {
    "S1": math.pi / 2,   # квадрантная машина,  N = 4
    "S2": math.pi / 3,   # секстантная машина,  N = 6
    "S3": math.pi / 7,   # 14-фазная машина,    N = 14
}


def cycle_length(theta: float) -> int:
    """Минимальное N: N·θ ≡ 0 (mod 2π). Для θ = π/k равно 2k (TS1)."""
    N = 1
    while (N * theta) % TAU > 1e-12 * TAU and N <= 4096:
        N += 1
    return N


class SpinorMachine:
    """Машина с единственным летучим регистром — спинорной фазой.

    Параметры
    ---------
    theta : шаг фазы θ (рад); для модельных фаз — из MODELS.
    phi0  : начальная фаза (по умолчанию 0 — каноническое состояние).

    Атрибут состояния ровно один: ``phi``. ``theta``/``N`` — константы
    спецификации модели (не меняются во время работы и не являются
    памятью: они известны наблюдателю до запуска машины).
    """

    __slots__ = ("theta", "N", "phi")

    def __init__(self, theta: float, phi0: float = 0.0):
        self.theta = float(theta)
        self.N = cycle_length(self.theta)
        self.phi = float(phi0) % TAU

    # ── исполнение в реальном времени ────────────────────────────────
    def step(self) -> float:
        """Один шаг: φ ← (φ + θ) mod 2π. O(1), без обращений к истории."""
        self.phi = (self.phi + self.theta) % TAU
        return self.phi

    def run(self, steps: int):
        """Генератор фаз по шагам (без сохранения истории)."""
        for _ in range(steps):
            yield self.step()

    def read(self) -> int:
        """Считывание состояния: ML-проекция фазы на решётку G_θ."""
        return int(round(self.phi / self.theta)) % self.N

    def reset(self) -> None:
        """Сброс: единственный регистр затирается каноническим значением.
        Пре-состояние НЕ сохраняется ни в каком виде (TS2)."""
        self.phi = 0.0

    # ── паспорт состояния ────────────────────────────────────────────
    def footprint(self) -> int:
        """Число изменяемых регистров состояния. Всегда 1 (только φ)."""
        return 1

    def state_bits(self) -> float:
        """Максимум информации в состоянии: log2 N бит (не растёт с t)."""
        return math.log2(self.N)


def state_footprint(machine: SpinorMachine) -> int:
    """Внешний аудит памяти: сколько изменяемых атрибутов у машины."""
    return len([a for a in machine.__slots__ if a == "phi"])
