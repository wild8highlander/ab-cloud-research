#!/usr/bin/env python3
"""Dynamic badge generator — renders shields-style SVG badges into .github/badges/
from the committed results registry (no external services, no API keys).
Values are traceable: edit SOURCES below to point at new run artifacts.
Commit policy is handled by the calling workflow (readme-badges.yml).
"""
import os, html

REPO = os.environ.get("REPO_ROOT", ".")
OUT = os.path.join(REPO, ".github", "badges")
os.makedirs(OUT, exist_ok=True)

# ---- badge definitions (left text, right text, color) -----------------------
# Update values by editing here or by extending to parse results/ JSON in CI.
BADGES = [
    ("julia-suite", "Julia suite", "39/39 PASS · two-pass", "#2EA043"),
    ("languages", "verification", "10/10 languages", "#00e5ff"),
    ("formal", "formal layer", "Lean4 8/8 · Coq · Agda · Isabelle", "#a78bfa"),
    ("zeros", "frozen ζ-zeros", "2,001,058 · SHA-256", "#4FC3F7"),
    ("spinor64", "spinor structures", "64/64 GUE-consistent", "#22c55e"),
]

MONO = "ui-monospace,'Cascadia Mono','JetBrains Mono',Menlo,Consolas,monospace"
CHAR_W = 6.6  # approx px per char at font-size 11


def badge_svg(left, right, color):
    lw = int(len(left) * CHAR_W) + 14
    rw = int(len(right) * CHAR_W) + 14
    w = lw + rw
    l, r = html.escape(left), html.escape(right)
    return f'''<svg xmlns="http://www.w3.org/2000/svg" width="{w}" height="20" role="img" aria-label="{l}: {r}">
  <linearGradient id="s" x2="0" y2="1">
    <stop offset="0" stop-color="#bbb" stop-opacity=".1"/>
    <stop offset="1" stop-opacity=".1"/>
  </linearGradient>
  <clipPath id="r"><rect width="{w}" height="20" rx="3" fill="#fff"/></clipPath>
  <g clip-path="url(#r)">
    <rect width="{lw}" height="20" fill="#0d1220"/>
    <rect x="{lw}" width="{rw}" height="20" fill="{color}"/>
    <rect width="{w}" height="20" fill="url(#s)"/>
  </g>
  <g fill="#e5e7eb" font-family="{MONO}" font-size="11">
    <text x="{lw // 2}" y="14" text-anchor="middle" fill="#c9d1d9">{l}</text>
    <text x="{lw + rw // 2}" y="14" text-anchor="middle">{r}</text>
  </g>
</svg>
'''


def main():
    for name, left, right, color in BADGES:
        path = os.path.join(OUT, f"{name}.svg")
        with open(path, "w", encoding="utf-8") as f:
            f.write(badge_svg(left, right, color))
        print(f"[ok] .github/badges/{name}.svg — {left}: {right}")

    # usage hint (idempotent, regenerated every run)
    with open(os.path.join(OUT, "README.md"), "w", encoding="utf-8") as f:
        f.write(
            "# Dynamic badges (auto-generated)\n\n"
            "Regenerated by `.github/workflows/readme-badges.yml` from the results registry.\n"
            "Reference them from any README as:\n\n"
            "```markdown\n"
            "![Julia suite](../../.github/badges/julia-suite.svg)\n"
            "```\n\n"
            "(adjust the relative path to the README depth)\n")


if __name__ == "__main__":
    main()
