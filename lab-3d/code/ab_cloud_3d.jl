# --- HELPER: form factor K(tau) at a single tau for a given unfolded spectrum
function form_factor_at_tau(unfolded::Vector{Float64}, tau::Float64)
    N = length(unfolded)
    if N == 0
        return 0.0
    end
    s = 0.0 + 0.0im
    @inbounds for u in unfolded
        s += exp(2pi * im * tau * u)
    end
    return abs2(s) / N
end

# --- HELPER: scan (alpha, sigma) -> mean_r phase diagram ---------------------
function scan_topo_phase(cfg::SimConfig; alpha_grid::Vector{Float64}, sigma_grid::Vector{Float64})
    results = Array{Float64, 2}(undef, length(sigma_grid), length(alpha_grid))
    for (j, a) in enumerate(alpha_grid)
        for (i, sg) in enumerate(sigma_grid)
            cfg_s = deepcopy(cfg)
            cfg_s.Lx = 6; cfg_s.Ly = 6; cfg_s.Lz = 3   # smaller for speed
            cfg_s.alpha = a
            cfg_s.sigma = sg
            cfg_s.nev = 30
            try
                H = build_hamiltonian_3d(cfg_s)
                evals, _ = eigs(H; nev=cfg_s.nev, sigma=0.0, which=:LM)
                _, _, mr, _ = unfold_ab_cloud(real.(evals); poly_deg=min(4, cfg.poly_deg))
                results[i, j] = mr
            catch e
                @warn "[topo_phase] alpha=$a sigma=$sg failed: $e"
                results[i, j] = NaN
            end
        end
    end
    return results
end

