@inline function node_index(x::Int, y::Int, z::Int, Lx::Int, Ly::Int)
    return x + (y - 1) * Lx + (z - 1) * Lx * Ly
end

function build_hamiltonian_3d(cfg::SimConfig)
    N = cfg.Lx * cfg.Ly * cfg.Lz
    rows = Int[]
    cols = Int[]
    vals = ComplexF64[]
    sizehint!(rows, 7 * N)
    sizehint!(cols, 7 * N)
    sizehint!(vals, 7 * N)

    gamma = (cfg.sigma - 0.5) * 2.0
    t_z_plus  = cfg.tz * exp(gamma)
    t_z_minus = cfg.tz * exp(-gamma)

    for z in 1:cfg.Lz, y in 1:cfg.Ly, x in 1:cfg.Lx
        i = node_index(x, y, z, cfg.Lx, cfg.Ly)
        V_rand = (rand() - 0.5) * cfg.disorder
        push!(rows, i); push!(cols, i); push!(vals, ComplexF64(V_rand))

        x_next = (x == cfg.Lx) ? 1 : x + 1
        j_x = node_index(x_next, y, z, cfg.Lx, cfg.Ly)
        push!(rows, i); push!(cols, j_x); push!(vals, ComplexF64(-1.0))
        push!(rows, j_x); push!(cols, i); push!(vals, ComplexF64(-1.0))

        y_next = (y == cfg.Ly) ? 1 : y + 1
        j_y = node_index(x, y_next, z, cfg.Lx, cfg.Ly)
        phase_y = exp(2im * pi * cfg.alpha * x)
        push!(rows, i); push!(cols, j_y); push!(vals, -1.0 * phase_y)
        push!(rows, j_y); push!(cols, i); push!(vals, -1.0 * conj(phase_y))

        if z < cfg.Lz
            j_z = node_index(x, y, z + 1, cfg.Lx, cfg.Ly)
            push!(rows, i); push!(cols, j_z); push!(vals, ComplexF64(-t_z_plus))
            push!(rows, j_z); push!(cols, i); push!(vals, ComplexF64(-t_z_minus))
        elseif cfg.bc_z == :PBC
            j_z = node_index(x, y, 1, cfg.Lx, cfg.Ly)
            push!(rows, i); push!(cols, j_z); push!(vals, ComplexF64(-t_z_plus))
            push!(rows, j_z); push!(cols, i); push!(vals, ComplexF64(-t_z_minus))
        end
    end
    return sparse(rows, cols, vals, N, N)
end

function run_3d_simulation(cfg::SimConfig)
    println("\n[3D] Построение разреженного 3D гамильтониана (N = $(cfg.Lx*cfg.Ly*cfg.Lz))...")
    H = build_hamiltonian_3d(cfg)
    println("[3D] Запуск ARPACK eigs (nev = $(cfg.nev), σ = $(cfg.target_shift))...")
    evals, evecs = eigs(H; nev=cfg.nev, sigma=cfg.target_shift, which=:LM)
    real_evals = real.(evals)
    sorted_E, norm_spacings, mean_r, unfolded = unfold_ab_cloud(real_evals; poly_deg=cfg.poly_deg)

    z_density = zeros(Float64, cfg.Lz)
    for state_idx in 1:cfg.nev
        psi = evecs[:, state_idx]
        for z in 1:cfg.Lz
            layer_mass = 0.0
            for y in 1:cfg.Ly, x in 1:cfg.Lx
                idx = node_index(x, y, z, cfg.Lx, cfg.Ly)
                layer_mass += abs2(psi[idx])
            end
            z_density[z] += layer_mass
        end
    end
    z_density ./= cfg.nev
    return evals, sorted_E, norm_spacings, mean_r, z_density, unfolded
end

