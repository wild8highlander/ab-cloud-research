# === 8. 3D EXCEPTIONAL POINTS LANDSCAPE =====================================
# Exceptional point: parameter pair (alpha, sigma) where two eigenvalues
# coalesce (same Re AND same Im). We track the minimum |dE| over all pairs.
function plot_3d_exceptional_points(cfg::SimConfig, run_dir::String)
    alpha_grid = collect(0.0:0.05:0.5)
    sigma_grid = collect(0.0:0.1:1.0)
    EP_surf = zeros(length(sigma_grid), length(alpha_grid))
    for (j, a) in enumerate(alpha_grid)
        for (i, sg) in enumerate(sigma_grid)
            cfg_s = deepcopy(cfg)
            cfg_s.Lz = 1
            cfg_s.alpha = a
            cfg_s.sigma = sg
            cfg_s.disorder = 0.0
            try
                H = build_hamiltonian_3d(cfg_s)
                F = eigen(Matrix(H))
                evals = F.values
                # Find smallest |dE| between any two eigenvalues
                min_dE = Inf
                for n in 1:length(evals)-1
                    for m in (n+1):length(evals)
                        dE = abs(evals[n] - evals[m])
                        if dE < min_dE
                            min_dE = dE
                        end
                    end
                end
                EP_surf[i, j] = min_dE
            catch e
                EP_surf[i, j] = NaN
            end
        end
    end
    p = plot(alpha_grid, sigma_grid, EP_surf, seriestype=:surface,
             xlabel="alpha", ylabel="sigma", zlabel="|dE| (минимальная щель)",
             title="3D ландшафт исключительных точек", dpi=300, camera=(45, 30))
    # Mark EP candidates: points where min |dE| < 0.1
    ep_xs = Float64[]; ep_ys = Float64[]; ep_zs = Float64[]
    for (j, a) in enumerate(alpha_grid), (i, sg) in enumerate(sigma_grid)
        if !isnan(EP_surf[i, j]) && EP_surf[i, j] < 0.1
            push!(ep_xs, a); push!(ep_ys, sg); push!(ep_zs, EP_surf[i, j])
        end
    end
    if !isempty(ep_xs)
        scatter!(p, ep_xs, ep_ys, ep_zs, ms=4, color=:red, label="кандидат EP (мин. |dE|)")
    end
    savefig(p, joinpath(run_dir, "3d_exceptional_points.png"))
    savefig(p, joinpath(run_dir, "3d_exceptional_points.pdf"))
    n_ep = length(ep_xs)
    return Dict("n_EP_candidates"=>n_ep, "min_min_dE"=>minimum(filter(!isnan, EP_surf)))
end

