function run_mode_zeta_rmt(cfg::SimConfig)
    println("\n>>> Режим: RMT-анализ встроенных нулей дзеты (KS, <r>)")
    run_dir, ts = make_run_dir(cfg, "zeta_RMT")
    z = load_embedded_zeros(cfg.n_zeros)
    n = length(z)
    zeros_all = z  # backward-compat
    unfolded = unfold_zeta_zeros(z)
    sp = diff(unfolded); sp = sp[sp .> 1e-6]; ns = sp ./ mean(sp)
    r_vals = Float64[]
    for i in 1:(length(ns)-1)
        s1 = ns[i]; s2 = ns[i+1]
        if s1 > 1e-6 && s2 > 1e-6
            push!(r_vals, min(s1,s2)/max(s1,s2))
        end
    end
    mean_r = mean(r_vals)
    D_g, p_g = ks_statistic(ns, gue_cdf)
    D_p, p_p = ks_statistic(ns, poisson_cdf)
    L_grid = Float64.(2:2:cfg.fs_L_max)
    d3 = delta_3_curve(unfolded, L_grid)
    s2 = sigma2_curve(unfolded, L_grid)
    d3_t = [delta3_gue_theory(L) for L in L_grid]
    s2_t = [sigma2_gue_theory(L) for L in L_grid]
    plot_rmt_results(unfolded, ns, mean_r, run_dir, L_grid, d3, d3_t, s2, s2_t)
    report = Dict(
        "timestamp" => ts,
        "mode"      => "zeta_RMT",
        "config"    => Dict(string(k)=>getfield(cfg,k) for k in fieldnames(SimConfig)),
        "zeros"     => Dict("embedded_total"=>length(zeros_all), "used"=>n,
                            "first"=>z[1], "last_used"=>z[end]),
        "zeta_RMT"  => Dict(
            "n_zeros"=>n, "mean_r"=>mean_r,
            "r_GUE_theory"=>0.5996, "r_Poisson"=>0.3863,
            "KS_vs_GUE_D"=>D_g, "KS_vs_GUE_p"=>p_g,
            "KS_vs_Poisson_D"=>D_p, "KS_vs_Poisson_p"=>p_p,
            "verdict_GUE"    => (p_g > 0.05 ? "ACCEPT" : (p_g > 0.01 ? "MARGINAL" : "REJECT")),
            "verdict_Poisson"=> (p_p > 0.05 ? "ACCEPT" : (p_p > 0.01 ? "MARGINAL" : "REJECT")),
            "refutes_reviewer_point_1_1"=>(p_g>0.05 && p_p<0.05),
        ),
        "rigidity"  => Dict(
            "L_grid"=>L_grid, "delta3_data"=>d3, "delta3_GUE"=>d3_t,
            "sigma2_data"=>s2, "sigma2_GUE"=>s2_t,
            "rel_err_delta3"=>mean(abs.(d3[.!isnan.(d3)].-d3_t[.!isnan.(d3)])./abs.(d3_t[.!isnan.(d3)])),
            "rel_err_sigma2"=>mean(abs.(s2[.!isnan.(s2)].-s2_t[.!isnan.(s2)])./abs.(s2_t[.!isnan.(s2)])),
        ),
    )
    r2a = !isnan(report["rigidity"]["rel_err_delta3"]) && report["rigidity"]["rel_err_delta3"] < 0.5 &&
           !isnan(report["rigidity"]["rel_err_sigma2"]) && report["rigidity"]["rel_err_sigma2"] < 0.5
    report["rigidity"]["refutes_reviewer_point_2a"] = r2a
    write_all_reports(report, run_dir, "zeta_RMT")
    println("\n[RMT] Готово. Папка: $run_dir")
end

