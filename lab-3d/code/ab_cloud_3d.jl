# Назначение:
#   1. 3D солвер неэрмитова топологического гамильтониана AB-Cloud (исходная программа пользователя, расширена).
#   2. Полная численная верификация препринта против рецензии:
#        • GUE/RMT статистика для нулей дзета-функции (KS, <r>, Δ₃(L), Σ²(L))
