# --- Риман–фон Мангольдт N(t) -------------------------------------------------
# # Формула: N(t) = (t/2π)·ln(t/2πe) + 7/8 + 1/(48π·t²)
# # Аналитическое unfolding для нулей дзеты — не требует полиномиальной аппроксимации.
function riemann_von_mangoldt_N(t::Float64)
    if t <= 0.0
        return 0.0
    end
    x = t / (2π)
    # Main term: (t/2π) · ln(t/2π) - t/2π = x·(ln x - 1)
    main = x * (log(x) - 1.0)
    # Subleading: 7/8
    sub = 7.0 / 8.0
    # 1/t² correction (small for t > 14)
    corr = 1.0 / (48π * t^2)
    return main + sub + corr
end

# --- UNFOLDING НУЛЕЙ ДЗЕТЫ ЧЕРЕЗ РИМАН–ФОН МАНГОЛЬДТА -----------------------------------------------------
function unfold_zeta_zeros(zeros::Vector{Float64})
    # # Аналитический разворот через N(t) Римана–фон Мангольдта
    # N(t) is the analytic Riemann-von Mangoldt cumulative zero count.
    # Its derivative N'(t) = (1/2π) ln(t/2π) gives the local mean density.
    # Setting unfolded[n] = N(t_n) makes spacings fluctuate around 1, with
    # the fluctuations matching the GUE distribution.
    unfolded_raw = [riemann_von_mangoldt_N(z) for z in zeros]
    # # Нормируем так, чтобы среднее расстояние = 1
    # Normalize so the global mean spacing equals 1 (removes the constant
    # offset between N(t_n) and n that comes from the missing S(T) term).
    sp = diff(unfolded_raw)
    μ = mean(sp)
    if μ <= 0 || isnan(μ) || isinf(μ)
        unfolded = collect(1.0:length(zeros))
    else
        unfolded = unfolded_raw ./ μ
    end
    # # Обрезаем края (10% с каждой стороны), где unfolding наименее точен (10% on each side)
    # Trimming removes edge regions where the RvM approximation is least
    # accurate (the S(T) term oscillates most near the endpoints).
    n = length(unfolded)
    n_trim = max(1, div(n, 20))
    if n > 4 * n_trim
        unfolded = unfolded[n_trim+1 : end-n_trim]
    end
    return unfolded
end

# --- UNFOLDING СПЕКТРА AB-CLOUD 3D --------------------------------------------------
function unfold_ab_cloud(real_evals::Vector{Float64}; poly_deg::Int=12)
    sorted_E = sort(real_evals)
    N = length(sorted_E)
    if N < 50
        # # Глобальный fit для малого N
        N_emp = collect(1.0:N)
        p = fit(sorted_E, N_emp, min(poly_deg, N-1))
        unfolded = [p(e) for e in sorted_E]
    else
        # # Обрезаем по 10% с краёв (внутренние 80%) — края где полиномиальный fit хуже всего
        n_trim = max(5, div(N, 10))   # 10% on each side → inner 80%
        inner_E = sorted_E[n_trim+1 : end-n_trim]
        inner_N = collect(Float64, n_trim+1 : N-n_trim)
        p = fit(inner_E, inner_N, min(poly_deg, length(inner_E)-1))
        unfolded = [p(e) for e in sorted_E]
    end
    sp = diff(unfolded)
    μ = mean(sp)
    if μ <= 0 || isnan(μ) || isinf(μ)
        unfolded = collect(1.0:N)
    else
        unfolded = unfolded ./ μ
    end
    # # Сохраняем только положительные spacings
    sp = diff(unfolded)
    valid = sp .> 1e-6
    if !all(valid)
        # плохих spacings (полиномиальный fit не идеален на краях)
        @warn "[unfold] $(sum(.!valid)) {{LANG_BAD_SPACINGS}}"
    end
    ns = sp ./ mean(sp[valid])
    r_vals = Float64[]
    for i in 1:(length(ns)-1)
        s1 = ns[i]; s2 = ns[i+1]
        if s1 > 1e-6 && s2 > 1e-6
            push!(r_vals, min(s1,s2)/max(s1,s2))
        end
    end
    mean_r = isempty(r_vals) ? NaN : mean(r_vals)
    return sorted_E, ns, mean_r, unfolded
end

# --- КУМУЛЯТИВНАЯ ФУНКЦИЯ РАСПРЕДЕЛЕНИЯ WIGNER-DYSON (GUE, β=2) ---------------------------------------------------------
# P(s) = (32/π²) s² exp(-4 s²/π); CDF via erf
function gue_cdf(s::Float64)
    if s <= 0
        return 0.0
    end
    return erf(2s/√π) - (4s/π) * exp(-4s^2/π)
end

function poisson_cdf(s::Float64)
    return s <= 0 ? 0.0 : 1.0 - exp(-s)
end

# --- KS-СТАТИСТИКА ---------------------------------------------------------
function ks_statistic(data::Vector{Float64}, cdf_func::Function)
    n = length(data)
    if n == 0
        return (0.0, 1.0)
    end
    sorted_data = sort(data)
    D = 0.0
    for i in 1:n
        F = cdf_func(sorted_data[i])
        D = max(D, abs(F - (i-1)/n), abs(F - i/n))
    end
    λ = (√n + 0.12 + 0.11/√n) * D
    # # Приближение Колмогорова для p-value
    Q_KS = 0.0
    for k in 1:100
        Q_KS += (-1)^(k-1) * exp(-2 * k^2 * λ^2)
    end
    Q_KS = 2 * Q_KS
    p_value = clamp(Q_KS, 0.0, 1.0)
    return (D, p_value)
end

# --- DYSON–MEHTA Δ₃(L) — СПЕКТРАЛЬНАЯ ЖЁСТКОСТЬ ----------------------------------------------------------
# # Стандартная Δ₃(L): среднеквадратичное отклонение числа уровней
# # в окне длины L от линейного тренда. Для GUE: Δ₃(L) ≈ (1/π²)(ln L + γ - 5/4).
# Standard Dyson-Mehta: for each window [u_i, u_i+L], fit a line n(u) = a + b*u
# to the staircase, and compute the average squared residual PER UNIT LENGTH.
# Dividing by L (≈ n_in) is critical — without it, the values grow linearly
# with L instead of logarithmically.
function delta_3_curve(unfolded::Vector{Float64}, L_grid::Vector{Float64})
    n = length(unfolded)
    delta3 = fill(NaN, length(L_grid))
    for (idx, L) in enumerate(L_grid)
        if L < 2 || L > n/3
            continue
        end
        cnt = 0
        s = 0.0
        # # Линейная регрессия внутри каждого окна — стандартный метод Dyson–Mehta
        for i in 1:(n - Int(ceil(L)) - 1)
            target = unfolded[i] + L
            j_end = i
            while j_end + 1 <= n && unfolded[j_end + 1] <= target
                j_end += 1
            end
            n_in = j_end - i + 1
            if n_in < 2
                continue
            end
            xs = unfolded[i:j_end] .- unfolded[i]
            ys = collect(0.0:(n_in-1))
            μ_x = mean(xs); μ_y = mean(ys)
            var_x = sum((xs .- μ_x).^2)
            if var_x > 1e-12
                b = sum((xs .- μ_x) .* (ys .- μ_y)) / var_x
                a = μ_y - b * μ_x
                residuals = ys .- (a .+ b .* xs)
                # Divide by n_in to get per-level variance (standard Δ₃ definition)
                s += sum(residuals.^2) / n_in
            else
                s += (n_in - L)^2 / n_in
            end
            cnt += 1
        end
        delta3[idx] = cnt > 0 ? s / cnt : NaN
    end
    return delta3
end

# --- Σ²(L) — ЧИСЛОВАЯ ДИСПЕРСИЯ ----------------------------------------------------------
# # Σ²(L) = <(N(L) - L)²>, где N(L) — число уровней в окне длины L.
# # Для GUE: Σ²(L) ≈ (2/π²)(ln(2π L) + γ - Ci(2π L) + cos(2π L)). Для Poisson: Σ²(L) = L.
function sigma2_curve(unfolded::Vector{Float64}, L_grid::Vector{Float64})
    n = length(unfolded)
    s2 = fill(NaN, length(L_grid))
    for (idx, L) in enumerate(L_grid)
        if L < 2 || L > n/3
            continue
        end
        cnt = 0
        s = 0.0
        counts_in = Float64[]
        for i in 1:(n - Int(ceil(L)) - 1)
            target = unfolded[i] + L
            j_end = i
            while j_end + 1 <= n && unfolded[j_end + 1] <= target
                j_end += 1
            end
            n_in = j_end - i + 1
            # # Используем регрессию для вычисления ожидаемого N(L)
            xs = unfolded[i:j_end] .- unfolded[i]
            ys = collect(0.0:(n_in-1))
            if n_in >= 2
                μ_x = mean(xs); μ_y = mean(ys)
                var_x = sum((xs .- μ_x).^2)
                if var_x > 1e-12
                    b = sum((xs .- μ_x) .* (ys .- μ_y)) / var_x
                    a = μ_y - b * μ_x
                    # # Остаток: разница между фактическим N и предсказанием регрессии в точке L
                    n_expected = a + b * L
                    push!(counts_in, n_in - n_expected)
                end
            end
            cnt += 1
        end
        if !isempty(counts_in)
            s2[idx] = mean(counts_in.^2)
        end
    end
    return s2
end

# --- Теоретическая Σ² для GUE ---
function sigma2_gue_theory(L::Float64)
    if L <= 0
        return 0.0
    end
    x = 2π * L
    # # Σ²(L) = (2/π²)(ln(2π L) + γ - Ci(2π L) + cos(2π L))
    # Standard Mehta formula: Σ²(L) = (2/π²)[ln(2π L) + γ + 1 - cos(2π L) - Ci(2π L)]
    # `cosint` is the SpecialFunctions.jl name for Ci(x).
    return (2/π^2) * (log(x) + 0.5772156649 + 1.0 - cos(x) - cosint(x))
end

# --- Теоретическая Δ₃ для GUE ---
function delta3_gue_theory(L::Float64)
    if L <= 0
        return 0.0
    end
    # # Δ₃(L) ≈ (1/π²)(ln L + γ - 5/4)
    return (1/π^2) * (log(L) + 0.5772156649 - 1.25)
end

# ==============================================================================
# ЧАСТЬ 4. ARF-ИНВАРИАНТ ПРИ ИЗМЕЛЬЧЕНИИ РЕШЁТКИ
# ==============================================================================
# # Для 2D-тора Arf квадратичной формы вычисляется через формулу
# # Arf = floor(2·α·Nx·Ny) mod 2 (Z₂ инвариант).
function arf_invariant(alpha::Float64, Nx::Int, Ny::Int)
    flux = alpha * Nx * Ny
    arf = mod(floor(Int, 2 * flux), 2)
    return arf
end

# # Проверяет сохранение Arf-инварианта при измельчении решётки Nx,Ny → 2Nx,2Ny (α·Nx·Ny = const).
function arf_refinement_test(alpha::Float64, levels::Int)
    results = Vector{Dict{String,Any}}()
    Nx = 4; Ny = 4
    base_flux = alpha * Nx * Ny
    for L in 0:levels
        # # Уровень измельчения
        Nx_L = Nx * (2^L); Ny_L = Ny * (2^L)
        alpha_L = base_flux / (Nx_L * Ny_L)
        a = arf_invariant(alpha_L, Nx_L, Ny_L)
        push!(results, Dict(
            "level" => L,
            "Nx"    => Nx_L,
            "Ny"    => Ny_L,
            "N"     => Nx_L * Ny_L,
            "alpha" => alpha_L,
            "arf"   => a,
        ))
    end
    arf_vals = [r["arf"] for r in results]
    preserved = all(==(arf_vals[1]), arf_vals)
    return results, preserved, arf_vals[1]
end

# ==============================================================================
# ЧАСТЬ 5. DECAY-TIME τ = ℏ/|Im E| И КАЛИБРОВКА E_typ
# ==============================================================================
# # Для каждого E_typ вычисляет матрицу H = H₀ + i(σ-1/2)Γ на 2D-решётке,
# # спектр E_n, типичное |Im E| для краевых мод (skin), и τ = ℏ/|Im E|.
function decay_time_analysis(cfg::SimConfig; E_typ_list::Vector{Float64}=[0.01,0.05,0.1,0.2,0.5,1.0])
    hbar_eV_s = 6.582119569e-16  # ℏ в эВ·с
    results = Vector{Dict{String,Any}}()
    cfg_local = deepcopy(cfg)
    cfg_local.Lx = 16; cfg_local.Ly = 16; cfg_local.Lz = 4
    cfg_local.sigma = 0.65   # неэрмитовость для демонстрации скин-эффекта
    cfg_local.nev = min(cfg_local.nev, 100)
    for E_typ in E_typ_list
        # # Строим гамильтониан с Γ-масштабированием
        cfg_local.disorder = 0.0
        H = build_hamiltonian_3d(cfg_local)
        # # Масштабируем гамильтониан так, что |t| = E_typ
        # (Hamiltonian already has unit t; rescale so |t| = E_typ)
        H_scaled = H * E_typ
        try
            evals, _ = eigs(H_scaled; nev=cfg_local.nev, sigma=0.0, which=:LM)
            im_vals = abs.(imag.(evals))
            # # Краевые моды — те, у которых |Im E| велика (skin)
            im_typ = isempty(im_vals) ? NaN : quantile(im_vals, 0.9)
            tau_s = im_typ > 0 ? hbar_eV_s / im_typ : NaN
            push!(results, Dict(
                "E_typ_eV"  => E_typ,
                "Im_typ_eV" => im_typ,
                "tau_s"     => tau_s,
                "tau_ps"    => tau_s * 1e12,
            ))
        catch e
            @warn "[decay] E_typ=$E_typ failed: $e"
            push!(results, Dict(
                "E_typ_eV"  => E_typ,
                "Im_typ_eV" => NaN,
                "tau_s"     => NaN,
                "tau_ps"    => NaN,
            ))
        end
    end
    # # Чувствительность: d(log τ)/d(log E_typ) через линейную регрессию
    valid = [r for r in results if !isnan(r["tau_s"])]
    if length(valid) >= 2
        logE = log.([r["E_typ_eV"] for r in valid])
        logτ = log.([r["tau_s"] for r in valid])
        μ_x = mean(logE); μ_y = mean(logτ)
        var_x = sum((logE .- μ_x).^2)
        slope = var_x > 1e-12 ? sum((logE .- μ_x) .* (logτ .- μ_y)) / var_x : NaN
    else
        slope = NaN
    end
    return results, slope
end

# ==============================================================================
# ЧАСТЬ 6. DIRAC CONE vs QED-РЕЖИМ
# ==============================================================================
# # Сравнивает α=0.5 (Dirac cone, β≈1) vs α≠0.5 (квадратичный режим, β≈2).
# # Вычисляет показатель степени дисперсии β через log-log регрессию.
function dirac_cone_analysis(cfg::SimConfig)
    cfg_local = deepcopy(cfg)
    cfg_local.sigma = 0.5  # эрмитов, только AB-фаза
    cfg_local.disorder = 0.0
    cfg_local.Lx = 12; cfg_local.Ly = 12; cfg_local.Lz = 1
    cfg_local.nev = min(cfg.nev, 100)
    cfg_local.alpha = 0.5
    H = build_hamiltonian_3d(cfg_local)
    evals, evecs = eigs(H; nev=cfg_local.nev, sigma=0.0, which=:LM)
    reals = real.(evals)
    # # Ищем Dirac-точку: минимум |E|
    idx_D = argmin(abs.(reals))
    E_D = reals[idx_D]
    # # Собираем пары (|k-k_D|, |E-E_D|) — индексы как прокси k
    pairs_k = Float64[]
    pairs_E = Float64[]
    for (k, E) in enumerate(reals)
        if abs(E - E_D) > 1e-6 && k != idx_D
            push!(pairs_k, Float64(abs(k - idx_D)))
            push!(pairs_E, abs(E - E_D))
        end
    end
    # # log-log регрессия для показателя степени β
    if length(pairs_k) >= 3
        logk = log.(pairs_k); logE = log.(pairs_E)
        μ_x = mean(logk); μ_y = mean(logE)
        var_x = sum((logk .- μ_x).^2)
        β = var_x > 1e-12 ? sum((logk .- μ_x) .* (logE .- μ_y)) / var_x : 2.0
    else
        β = 2.0
    end
    is_dc = 0.7 < β < 1.3
    me_c2_eV = 0.511e6  # масса электрона в эВ
    return Dict(
        "alpha" => cfg_local.alpha,
        "E_Dirac" => E_D,
        "dispersion_exponent_beta" => β,
        "is_dirac_cone" => is_dc,
        "me_c2_eV" => me_c2_eV,
        "n_pairs" => length(pairs_k),
    )
end

# ==============================================================================
# ЧАСТЬ 7. FINITE-SIZE SCALING (N → ∞)
# ==============================================================================
# # Запускает 3D-солвер для нескольких размеров Lx=Ly и проверяет сходимость <r> → 0.5996.
# # Также выполняет то же для встроенных нулей дзеты (нарезка по n_zeros).
function finite_size_scaling(cfg::SimConfig; rng=Random.GLOBAL_RNG)
    ab_results = Vector{Dict{String,Any}}()
    L_sizes = [4, 6, 8, 10, 12]
    for L in L_sizes
        cfg_L = deepcopy(cfg)
        cfg_L.Lx = L; cfg_L.Ly = L; cfg_L.Lz = 4
        cfg_L.nev = min(cfg.nev, max(20, L*L*4 ÷ 4))
        try
            H = build_hamiltonian_3d(cfg_L)
            evals, _ = eigs(H; nev=cfg_L.nev, sigma=0.0, which=:LM)
            _, _, mean_r_L, _ = unfold_ab_cloud(real.(evals); poly_deg=min(8, cfg.poly_deg))
            push!(ab_results, Dict(
                "L" => L,
                "mean_r" => mean_r_L,
                "abs_diff_GUE" => abs(mean_r_L - 0.5996),
                "N" => L*L*4,
            ))
        catch e
            @warn "[FSS] L=$L failed: $e"
        end
    end

    # # FSS для нулей дзеты: нарезаем по n_zeros
    zeta_results = Vector{Dict{String,Any}}()
    all_zeros = load_embedded_zeros()
    N_list = [100, 200, 500, 1000, 2000, 5000]
    for n_zeros in N_list
        n_zeros = min(n_zeros, length(all_zeros))
        z = all_zeros[1:n_zeros]
        unfolded = unfold_zeta_zeros(z)
        sp = diff(unfolded)
        sp = sp[sp .> 1e-6]
        if length(sp) < 2
            continue
        end
        ns = sp ./ mean(sp)
        r_vals = Float64[]
        for i in 1:(length(ns)-1)
            s1 = ns[i]; s2 = ns[i+1]
            if s1 > 1e-6 && s2 > 1e-6
                push!(r_vals, min(s1,s2)/max(s1,s2))
            end
        end
        mean_r = isempty(r_vals) ? NaN : mean(r_vals)
        D_g, p_g = ks_statistic(ns, gue_cdf)
        push!(zeta_results, Dict(
            "n_zeros" => n_zeros,
            "mean_r" => mean_r,
            "abs_diff_GUE" => abs(mean_r - 0.5996),
            "KS_p_value" => p_g,
        ))
    end
    return ab_results, zeta_results
end

