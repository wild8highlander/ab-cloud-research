#   4. S(T) = N(T) - N_bar(T) fluctuation with theoretical variance
#   5. RH line check (all 5000 zeros on Re(s)=1/2 by construction)
#   6. Decay-time mapping tau_n = hbar/gamma_n  (direct physical interpretation)

# --- WIGNER-DYSON GUE NEAREST-NEIGHBOR PDF ------------------------------------
function wigner_dyson_pdf(s::Float64)
    if s < 0
        return 0.0
    end
    return (32.0 / pi^2) * s^2 * exp(-4.0 * s^2 / pi)
end

# --- POISSON NN PDF (for comparison) ------------------------------------------
function poisson_pdf(s::Float64)
    return s < 0 ? 0.0 : exp(-s)
end

# --- GUE PAIR CORRELATION  R_2(x) = 1 - (sin(pi x)/(pi x))^2 ------------------
function gue_pair_correlation(x::Float64)
    if abs(x) < 1e-12
        return 1.0
    end
    sx = sin(pi * x) / (pi * x)
    return 1.0 - sx^2
end

# --- GUE SPECTRAL FORM FACTOR  K(tau) = tau (tau<1), 1 (tau>=1) ----------------
function gue_form_factor(tau::Float64)
    return tau <= 1.0 ? tau : 1.0
end

# --- S(T) = N_actual(T) - N_smooth(T)  ---------------------------------------
# N_actual = index n (since zeros are sorted gamma_n)
# N_smooth = Riemann-von Mangoldt N(T) (analytic smooth part)
function compute_S_T(zeros::Vector{Float64})
    N = length(zeros)
    S = Vector{Float64}(undef, N)
    @inbounds for n in 1:N
        T = zeros[n]
        S[n] = Float64(n) - riemann_von_mangoldt_N(T)
    end
    return S
end

# --- RH VERIFICATION: all embedded zeros have Re(s)=1/2 ----------------------
# The embedded table stores only the imaginary parts gamma_n. By construction
# of the Odlyzko-Schonhage table, all gamma_n correspond to non-trivial zeros
# rho_n = 1/2 + i*gamma_n of the Riemann zeta function, i.e. they all lie on
# the critical line Re(s)=1/2.
function verify_rh(zeros::Vector{Float64})
    return all(z -> z > 0.0 && isfinite(z), zeros)
end

# --- DECAY-TIME MAPPING  tau_n = hbar/gamma_n  --------------------------------
# In the AB-Cloud non-Hermitian Hamiltonian at sigma=1/2 (RH critical line),
# each Riemann zero gamma_n corresponds to an imaginary eigenvalue
# E_n = i*gamma_n, giving a decay time tau_n = hbar/|Im(E_n)| = hbar/gamma_n.
function decay_time_from_zeros(zeros::Vector{Float64}; hbar::Float64=1.0)
    return Float64[hbar / z for z in zeros if z > 0.0]
end

# --- PLOT: NN-spacing histogram + Wigner-Dyson fit ---------------------------
function plot_nn_spacing_pdf(ns::Vector{Float64}, run_dir::String)
    p = histogram(ns, bins=0.0:0.05:4.0, normalize=:pdf,
                  label="нули дзеты (n=$(length(ns)))",
