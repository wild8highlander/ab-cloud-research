end

# === 5. 3D WINDING NUMBER W(alpha, sigma) ===================================
# Non-Hermitian topological invariant: W = (1/2pi) * dphi/dalpha
# where phi = arg(det[D(k=0, alpha, sigma)]) - off-diagonal block determinant.
# For simplicity, we use the spectrum-based proxy:
# W(alpha, sigma) = sign change of (E_+ - E_-) at the gap center
function compute_winding_2d(cfg::SimConfig, alpha::Float64, sigma::Float64)
    cfg_s = deepcopy(cfg)
    cfg_s.Lz = 1
    cfg_s.alpha = alpha
    cfg_s.sigma = sigma
    cfg_s.disorder = 0.0
    H = build_hamiltonian_3d(cfg_s)
    F = eigen(Matrix(H))
    evals = F.values
    sort!(evals, by=imag)
    N = length(evals)
    n_occ = div(N, 2)
    # Gap = E_{n_occ+1} - E_{n_occ}
    gap = real(evals[n_occ+1]) - real(evals[n_occ])
    # Winding proxy: count imaginary eigenvalue crossings
    imag_part = imag.(evals[n_occ:n_occ+1])
    return gap, imag_part[2] - imag_part[1]
end

function plot_3d_winding_number(cfg::SimConfig, run_dir::String)
    alpha_grid = collect(0.0:0.05:0.5)
    sigma_grid = collect(0.0:0.1:1.0)
    W_surf = zeros(length(sigma_grid), length(alpha_grid))
    for (j, a) in enumerate(alpha_grid)
        for (i, sg) in enumerate(sigma_grid)
            try
                gap, dim = compute_winding_2d(cfg, a, sg)
                # Winding: 1 if gap < 0.5 (topological), 0 if gap > 1 (trivial)
                W_surf[i, j] = gap < 0.5 ? 1.0 : 0.0
            catch e
                W_surf[i, j] = NaN
            end
        end
    end
    p = plot(alpha_grid, sigma_grid, W_surf, seriestype=:surface,
             xlabel="alpha (поток AB)", ylabel="sigma (неэрмитовость)", zlabel="W",
             title="3D число намотки W(alpha, sigma) - неэрмитова топология", dpi=300, camera=(45, 30))
    rh_y = fill(0.5, length(alpha_grid))
    rh_z = fill(1.0, length(alpha_grid))
    plot!(p, alpha_grid, rh_y, rh_z, lw=3, ls=:dash, label="RH-прямая (sigma=0.5)")
    savefig(p, joinpath(run_dir, "3d_winding_number.png"))
    savefig(p, joinpath(run_dir, "3d_winding_number.pdf"))
    return Dict("alpha_grid"=>alpha_grid, "sigma_grid"=>sigma_grid,
                "W_at_RH"=>(length(sigma_grid) >= 6 ? W_surf[6, :] : Float64[]))
end

