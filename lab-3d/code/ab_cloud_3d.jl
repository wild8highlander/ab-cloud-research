# --- PLOT: pair correlation R_2(x) -------------------------------------------
function plot_pair_correlation(unfolded::Vector{Float64}, run_dir::String)
    diffs = Float64[]
    N = length(unfolded)
    window = min(20, max(2, N ÷ 50))
    @inbounds for n in 1:N
        mmax = min(n + window, N)
        for m in (n+1):mmax
            d = unfolded[m] - unfolded[n]
            if 0.0 < d < 5.0
                push!(diffs, d)
            end
        end
    end
    if isempty(diffs)
        @warn "[pair_corr] no diffs collected"
        return diffs
    end
    p = histogram(diffs, bins=0.0:0.05:5.0, normalize=:pdf,
                  label="нули дзеты (пар=$(length(diffs)))",
                  xlabel="x = (u_n - u_m)",
                  ylabel="R_2(x)",
                  title="Парная корреляция - Монтгомери-Одлижко",
                  legend=:topright, dpi=300, lw=0)
    x_grid = collect(0.001:0.01:5.0)
    gue_R2 = [gue_pair_correlation(x) for x in x_grid]
    plot!(p, x_grid, gue_R2, lw=2, label="GUE: 1 - (sin pi x / pi x)^2")
    savefig(p, joinpath(run_dir, "pair_correlation_R2.png"))
    savefig(p, joinpath(run_dir, "pair_correlation_R2.pdf"))
    return diffs
end

# --- PLOT: spectral form factor K(tau) ---------------------------------------
function plot_form_factor(unfolded::Vector{Float64}, run_dir::String)
    N = length(unfolded)
    tau_grid = collect(0.0:0.01:2.0)
    K_emp = Vector{Float64}(undef, length(tau_grid))
    @inbounds for (i, tau) in enumerate(tau_grid)
        s = 0.0 + 0.0im
        for u in unfolded
            s += exp(2pi * im * tau * u)
        end
        K_emp[i] = abs2(s) / N
    end
    p = plot(tau_grid, K_emp, lw=2, label="нули дзеты (эмпирически)",
             xlabel="tau", ylabel="K(tau)",
             title="Спектральный форм-фактор - GUE", legend=:topright, dpi=300)
    K_gue = [gue_form_factor(tau) for tau in tau_grid]
    plot!(p, tau_grid, K_gue, lw=2, ls=:dash, label="GUE: K(tau)=tau (tau<1), 1 (tau>=1)")
    savefig(p, joinpath(run_dir, "form_factor_K.png"))
    savefig(p, joinpath(run_dir, "form_factor_K.pdf"))
    return Dict("tau"=>tau_grid, "K_empirical"=>K_emp, "K_GUE"=>K_gue)
end

# --- PLOT: S(T) fluctuation with theoretical +/- sigma band ------------------
function plot_S_T(zeros::Vector{Float64}, run_dir::String)
    S = compute_S_T(zeros)
    T = zeros
    var_theory = (1.0 / (2pi^2)) .* log.(T ./ (2pi))
    var_theory = max.(var_theory, 0.0)
    sigma_theory = sqrt.(var_theory)
    p = plot(T, S, lw=1, label="S(T) = N(T) - N_сглаж(T)",
             xlabel="T = gamma_n", ylabel="S(T)",
             title="Флуктуация S(T) нулей дзеты", legend=:topright, dpi=300)
    plot!(p, T,  sigma_theory, lw=2, ls=:dash, label="+/-sigma_теор = sqrt(ln(T/2pi)/2pi^2)")
    plot!(p, T, -sigma_theory, lw=2, ls=:dash, label="")
    savefig(p, joinpath(run_dir, "S_T_fluctuation.png"))
    savefig(p, joinpath(run_dir, "S_T_fluctuation.pdf"))
    return Dict("T"=>T, "S"=>S, "sigma_theory"=>sigma_theory,
                "mean_S"=>mean(S), "var_S"=>var(S))
end

# --- PLOT: decay-time distribution tau_n = hbar/gamma_n ----------------------
function plot_decay_time_from_zeros(zeros::Vector{Float64}, run_dir::String)
    tau = decay_time_from_zeros(zeros)
    tau_sorted = sort(tau, rev=true)   # slowest-decaying first
    n_grid = collect(1:length(tau_sorted))
    # Asymptotic: gamma_n ~ 2pi n / ln(n/2pi)  =>  tau_n ~ ln(n/2pi) / (2pi n)
    eps = 1e-6
    tau_pred = [max(eps, log(max(eps, k/(2pi))) / (2pi * k)) for k in n_grid]
    p = plot(n_grid, tau_sorted, lw=1, yscale=:log10,
             label="tau_n = hbar/gamma_n",
             xlabel="n (сорт. по tau)", ylabel="tau (лог. шкала)",
             title="Распределение времён распада из нулей Римана", legend=:topright, dpi=300)
    plot!(p, n_grid, tau_pred, lw=2, ls=:dash, label="асимптотика: 2pi/(n ln(n/2pi))")
    savefig(p, joinpath(run_dir, "decay_time_from_zeros.png"))
    savefig(p, joinpath(run_dir, "decay_time_from_zeros.pdf"))
    return Dict("n"=>n_grid, "tau"=>tau_sorted, "tau_asymptotic"=>tau_pred)
end

