# --- LOCAL CHERN MARKER (Bianco-Resta) --------------------------------------
# C(r) = -4*pi * Im[<r| P X P Y P - P Y P X P |r>]
# where P = projector onto occupied (low-energy) subspace
# For 2D slice at z = z_layer. Uses FULL diagonalization (small matrix).
function local_chern_marker_2d(cfg::SimConfig, z_layer::Int=1)
    cfg_2d = deepcopy(cfg)
    cfg_2d.Lz = 1
    H = build_hamiltonian_3d(cfg_2d)
    N = cfg_2d.Lx * cfg_2d.Ly

    # Full diagonalization (small matrix)
    F = eigen(Matrix(H))
    evals = F.values
    evecs = F.vectors

    # Occupied = bottom half (insulating gap assumed)
    n_occ = div(N, 2)
    P = zeros(ComplexF64, N, N)
    for n in 1:n_occ
        psi = view(evecs, :, n)
        P .+= psi * psi'
    end

    # Position operators (diagonal)
    X = zeros(Float64, N, N)
    Y = zeros(Float64, N, N)
    for y in 1:cfg_2d.Ly, x in 1:cfg_2d.Lx
        i = node_index(x, y, 1, cfg_2d.Lx, cfg_2d.Ly)
        X[i, i] = x
        Y[i, i] = y
    end

    # Local Chern marker matrix
    M = P * X * P * Y * P - P * Y * P * X * P
    c_local = [-4pi * imag(M[i, i]) for i in 1:N]

    c_grid = reshape(c_local, cfg_2d.Lx, cfg_2d.Ly)
    avg_C = sum(c_local) / N
    return c_grid, avg_C, n_occ, N
end

# --- EDGE STATE LOCALIZATION (3D scatter of |psi|^2) ------------------------
function find_edge_state(cfg::SimConfig)
    H = build_hamiltonian_3d(cfg)
    evals, evecs = eigs(H; nev=10, sigma=0.0, which=:LM)
    # Edge state = closest to zero energy AND localized at boundary
    best_idx = 1
    best_score = -Inf
    for n in 1:size(evecs, 2)
        psi = evecs[:, n]
        density = abs2.(psi)
        density ./= (sum(density) + 1e-12)
        # Score = (boundary weight) - (bulk weight)
        edge_w = 0.0
        bulk_w = 0.0
        for z in 1:cfg.Lz, y in 1:cfg.Ly, x in 1:cfg.Lx
            i = node_index(x, y, z, cfg.Lx, cfg.Ly)
            is_edge = (x == 1 || x == cfg.Lx || y == 1 || y == cfg.Ly || z == 1 || z == cfg.Lz)
            if is_edge
                edge_w += density[i]
            else
                bulk_w += density[i]
            end
        end
        score = edge_w - bulk_w
        if score > best_score
            best_score = score
            best_idx = n
        end
    end
    return evecs[:, best_idx], evals[best_idx], best_score
end

# --- PROBABILITY CURRENT J on every bond ------------------------------------
# J_{i->j} = 2 * Im[psi_i^* H_{ij} psi_j]
function compute_probability_current_3d(cfg::SimConfig, psi::Vector{ComplexF64})
    xs = Float64[]; ys = Float64[]; zs = Float64[]
    jxs = Float64[]; jys = Float64[]; jzs = Float64[]

    gamma = (cfg.sigma - 0.5) * 2.0
    t_z_plus  = cfg.tz * exp(gamma)
    t_z_minus = cfg.tz * exp(-gamma)

    for z in 1:cfg.Lz, y in 1:cfg.Ly, x in 1:cfg.Lx
        i = node_index(x, y, z, cfg.Lx, cfg.Ly)

        # X-bond
        x_next = (x == cfg.Lx) ? 1 : x + 1
        j_x = node_index(x_next, y, z, cfg.Lx, cfg.Ly)
        H_ij = -1.0
        curr = 2 * imag(conj(psi[i]) * H_ij * psi[j_x])
        push!(xs, (x + x_next) / 2); push!(ys, Float64(y)); push!(zs, Float64(z))
        push!(jxs, curr); push!(jys, 0.0); push!(jzs, 0.0)

        # Y-bond
        y_next = (y == cfg.Ly) ? 1 : y + 1
        j_y = node_index(x, y_next, z, cfg.Lx, cfg.Ly)
        phase_y = exp(2im * pi * cfg.alpha * x)
        H_ij = -phase_y
        curr = 2 * imag(conj(psi[i]) * H_ij * psi[j_y])
        push!(xs, Float64(x)); push!(ys, (y + y_next) / 2); push!(zs, Float64(z))
        push!(jxs, 0.0); push!(jys, curr); push!(jzs, 0.0)

        # Z-bond
        if z < cfg.Lz
            j_z = node_index(x, y, z + 1, cfg.Lx, cfg.Ly)
            H_ij = -t_z_plus
            curr = 2 * imag(conj(psi[i]) * H_ij * psi[j_z])
            push!(xs, Float64(x)); push!(ys, Float64(y)); push!(zs, (z + z + 1) / 2)
            push!(jxs, 0.0); push!(jys, 0.0); push!(jzs, curr)
        end
    end
    return xs, ys, zs, jxs, jys, jzs
end

