def decay_time_analysis(cfg: SimConfig, E_typ_list: Optional[List[float]] = None) -> List[Dict[str, Any]]:
    """Compute decay time τ = ℏ/E_typ for a list of typical energies."""
    if E_typ_list is None:
        E_typ_list = [0.01, 0.05, 0.1, 0.2, 0.5, 1.0]
    hbar = 1.0
    results = []
    for E in E_typ_list:
        tau = hbar / max(E, 1e-9)
        results.append({"E_typ": E, "tau": tau, "hbar": hbar})
    return results


