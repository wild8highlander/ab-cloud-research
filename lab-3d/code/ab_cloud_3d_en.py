def dirac_cone_analysis(cfg: SimConfig) -> Dict[str, Any]:
    """Analyze Dirac cone structure in the spectrum."""
    sim = run_3d_simulation(cfg)
    real_E = sim["real_E"]
    # Find band center
    E_min, E_max = real_E.min(), real_E.max()
    E_mid = 0.5 * (E_min + E_max)
    # Linear fit near E_mid
    window = max(0.05 * (E_max - E_min), 1e-3)
    mask = np.abs(real_E - E_mid) < window
    if mask.sum() < 3:
        return {"E_mid": float(E_mid), "slope": 0.0, "n_cone_states": int(mask.sum())}
    E_in = real_E[mask]
    k_in = np.arange(len(E_in), dtype=float) - len(E_in) / 2
    try:
        coeffs = np.polyfit(k_in, E_in, 1)
        slope = float(coeffs[0])
    except Exception:
        slope = 0.0
    return {
        "E_mid": float(E_mid),
        "slope": slope,
        "n_cone_states": int(mask.sum()),
        "window": float(window),
    }


