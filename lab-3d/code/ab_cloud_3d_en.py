# PART 6. ARF INVARIANT
# ==============================================================================

def arf_invariant(alpha: float, Nx: int, Ny: int) -> float:
    """Arf invariant for 2D AB-Cloud: K = (1/2)·sin(2πα)·mod(Nx·Ny, 2)."""
    return 0.5 * math.sin(2 * math.pi * alpha) * ((Nx * Ny) % 2)


def arf_refinement_test(alpha: float, levels: int) -> List[Dict[str, Any]]:
    """Test Arf invariant under mesh refinement."""
    results = []
    for L in range(1, levels + 1):
        Nx = 2 ** L
        Ny = 2 ** L
        K = arf_invariant(alpha, Nx, Ny)
        results.append({"level": L, "Nx": Nx, "Ny": Ny, "Arf_K": K})
    return results


