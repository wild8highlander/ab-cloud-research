def local_chern_marker_2d(cfg: SimConfig, z_layer: int = 1) -> np.ndarray:
    """Bianco-Resta local Chern marker C(r) for a 2D slice."""
    Lx, Ly = cfg.Lx, cfg.Ly
    # Build a 2D Hamiltonian for the slice (single layer)
    H = np.zeros((Lx * Ly * 2, Lx * Ly * 2), dtype=complex)
    def idx(x, y, s):
        return ((y * Lx + x) * 2 + s)
    for y in range(Ly):
        for x in range(Lx):
            iA = idx(x, y, 0)
            phase_x = 1.0 if (y % 2 == 0) else -1.0
            phase_y = 1.0 if (x % 2 == 0) else -1.0
            if x + 1 < Lx:
                iB = idx(x + 1, y, 1)
                H[iA, iB] += 1.0 + 1j * cfg.alpha * phase_x
                H[iB, iA] += 1.0 - 1j * cfg.alpha * phase_x
            if y + 1 < Ly:
                iB = idx(x, y + 1, 1)
                H[iA, iB] += 1.0 + 1j * cfg.alpha * phase_y
                H[iB, iA] += 1.0 - 1j * cfg.alpha * phase_y
    evals, evecs = eig(H)
    # Occupied states (lower half)
    n_occ = len(evals) // 2
    idx_sort = np.argsort(evals.real)
    occ_vecs = evecs[:, idx_sort[:n_occ]]
    # Projector
    P = occ_vecs @ occ_vecs.conj().T
    # Position operators
    pos_x = np.zeros(H.shape, dtype=complex)
    pos_y = np.zeros(H.shape, dtype=complex)
    for y in range(Ly):
        for x in range(Lx):
            for s in range(2):
                i = idx(x, y, s)
                pos_x[i, i] = x
                pos_y[i, i] = y
    # Compute C(r) = -4π·Im[<r|P·X·P·Y·P - P·Y·P·X·P|r>]
    PXP = P @ pos_x @ P
    PYP = P @ pos_y @ P
    PXPYP = PXP @ PYP
    PYPXP = PYP @ PXP
    comm = PXPYP - PYPXP
    C = np.zeros((Ly, Lx))
    for y in range(Ly):
        for x in range(Lx):
            for s in range(2):
                i = idx(x, y, s)
                C[y, x] += -4 * math.pi * comm[i, i].imag
            C[y, x] /= 2
    return C


def find_edge_state(cfg: SimConfig) -> Dict[str, Any]:
    """Find a boundary-localized eigenstate of the 3D Hamiltonian."""
    sim = run_3d_simulation(cfg)
    evals, evecs = eig(sim["H"])
    # Find eigenstate with highest boundary-to-bulk ratio
    Lx, Ly, Lz = cfg.Lx, cfg.Ly, cfg.Lz
    n_bulk = max(1, (Lx - 2) * (Ly - 2) * max(1, Lz - 2) * 2)
    n_edge = sim["H"].shape[0] - n_bulk
    edge_score_max = -1
    best_idx = 0
    best_E = 0
    for i in range(min(len(evals), 50)):
        psi = evecs[:, i]
        density = np.abs(psi) ** 2
        # Compute edge vs bulk density
        edge_d = 0.0
        bulk_d = 0.0
        for z in range(Lz):
            for y in range(Ly):
                for x in range(Lx):
                    for s in range(2):
                        idx = ((z * Ly + y) * Lx + x) * 2 + s
                        if idx < len(density):
                            d = density[idx]
                            if x == 0 or x == Lx-1 or y == 0 or y == Ly-1 or z == 0 or z == Lz-1:
                                edge_d += d
                            else:
                                bulk_d += d
        if bulk_d > 1e-12:
            score = edge_d / (edge_d + bulk_d)
        else:
            score = 1.0
        if score > edge_score_max:
            edge_score_max = score
            best_idx = i
            best_E = float(evals[i].real)
    return {"edge_state_E": best_E, "edge_score": edge_score_max, "n_states_scanned": min(len(evals), 50)}


