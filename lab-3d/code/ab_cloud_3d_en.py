def finite_size_scaling(cfg: SimConfig) -> Dict[str, Any]:
    """Run simulations at multiple lattice sizes; extract ⟨r⟩ vs N."""
    sizes = [4, 6, 8, 10, 12]
    ab_fss = []
    for L in sizes:
        cfg2 = SimConfig(Lx=L, Ly=L, Lz=L, tz=cfg.tz, sigma=cfg.sigma,
                         alpha=cfg.alpha, disorder=cfg.disorder,
                         bc_z=cfg.bc_z, nev=cfg.nev, n_zeros=cfg.n_zeros,
                         poly_deg=cfg.poly_deg, fs_L_max=cfg.fs_L_max,
                         arf_levels=cfg.arf_levels, out_dir=cfg.out_dir)
        try:
            sim = run_3d_simulation(cfg2)
            ab_fss.append({"L": L, "N": L**3 * 2, "mean_r": sim["mean_r"]})
        except Exception as e:
            ab_fss.append({"L": L, "N": L**3 * 2, "mean_r": float('nan'), "error": str(e)})
    # Zeta zeros FSS (analytical: ⟨r⟩ → 0.6027 as n→∞)
    zeta_fss = []
    for n_z in [100, 500, 1000, 2000, 5000]:
        if n_z > cfg.n_zeros:
            continue
        z = load_embedded_zeros(n_z)[:n_z]
        unfolded = unfold_zeta_zeros(z)
        sp = np.diff(unfolded)
        sp = sp[sp > 1e-6]
        ns = sp / sp.mean()
        if len(ns) > 1:
            r_vals = np.minimum(ns[:-1], ns[1:]) / np.maximum(ns[:-1], ns[1:])
            mean_r = float(r_vals.mean())
        else:
            mean_r = 0.0
        zeta_fss.append({"n_zeros": n_z, "mean_r": mean_r})
    return {"ab_fss": ab_fss, "zeta_fss": zeta_fss}


