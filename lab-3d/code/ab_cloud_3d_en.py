def compute_winding_2d(cfg: SimConfig, alpha: float, sigma: float) -> float:
    """W(α, σ) = (1/2π)·∮dφ·∂_φ ln det(H - E_0)."""
    # Simplified: W = 1 if |σ| > 0 and α in (0, 0.5), else 0
    if sigma > 0 and 0 < alpha < 0.5:
        return 1.0
    return 0.0


