def riemann_von_mangoldt_N(t: float) -> float:
    """N(t) ≈ (t/2π)·ln(t/2πe) + 11/8."""
    if t <= 0:
        return 0.0
    u = t / (2 * math.pi)
    return u * (math.log(u) - 1.0) + 11.0 / 8.0


def unfold_zeta_zeros(zeros: List[float]) -> np.ndarray:
    """Unfold zeta zeros via Riemann-von Mangoldt: x_n = N(t_n) - 1/2."""
    return np.array([riemann_von_mangoldt_N(t) - 0.5 for t in zeros])


def unfold_ab_cloud(real_evals: List[float], poly_deg: int = 12) -> np.ndarray:
    """Unfold a generic spectrum via polynomial fit to the staircase."""
    E = np.sort(np.asarray(real_evals, dtype=float))
    if len(E) < 4:
        return E
    n = np.arange(1, len(E) + 1, dtype=float)
    # Fit polynomial of degree poly_deg
    deg = min(poly_deg, len(E) - 2)
    if deg < 1:
        deg = 1
    coeffs = np.polyfit(E, n, deg)
    fit = np.polyval(coeffs, E)
    unfolded = np.diff(fit)
    unfolded = unfolded[unfolded > 1e-9]
    if len(unfolded) > 0:
        unfolded = unfolded / unfolded.mean()
    return unfolded


def gue_cdf(s: float) -> float:
    """GUE Wigner-Dyson nearest-neighbor spacing CDF (Wigner surmise)."""
    if s <= 0:
        return 0.0
    return 1.0 - math.exp(-(math.pi / 4) * s * s)


def poisson_cdf(s: float) -> float:
    """Poisson spacing CDF: 1 - exp(-s)."""
    if s <= 0:
        return 0.0
    return 1.0 - math.exp(-s)


def ks_statistic(data: np.ndarray, cdf_func: Callable[[float], float]) -> Tuple[float, float]:
    """Compute KS D statistic and approximate p-value."""
    if len(data) == 0:
        return (float('nan'), float('nan'))
    sorted_data = np.sort(data)
    n = len(sorted_data)
    cdf_vals = np.array([cdf_func(x) for x in sorted_data])
    d_plus = np.max(np.arange(1, n + 1) / n - cdf_vals)
    d_minus = np.max(cdf_vals - np.arange(0, n) / n)
    D = max(d_plus, d_minus)
    # Approximate p-value (Kolmogorov)
    en = math.sqrt(n)
    p = 0.0
    try:
        # Use scipy.stats.kstest for proper p-value
        result = kstest(sorted_data, cdf_func)
        p = float(result.pvalue)
    except Exception:
        # Fallback asymptotic formula
        lam = (en + 0.12 + 0.11 / en) * D
        p = max(0.0, min(1.0, 2.0 * math.exp(-2.0 * lam * lam)))
    return (float(D), p)


def delta_3_curve(unfolded: np.ndarray, L_grid: np.ndarray) -> np.ndarray:
    """Dyson-Mehta Δ₃(L) statistic. Measures spectral rigidity."""
    if len(unfolded) < 5:
        return np.zeros_like(L_grid)
    N = len(unfolded)
    cumulative = np.concatenate([[0], np.cumsum(unfolded)])
    # cumulative[i] = number of levels up to position i (in units of mean spacing)
    result = []
    for L in L_grid:
        L = float(L)
        if L < 1:
            result.append(0.0)
            continue
        max_start = max(0, N - int(L) - 1)
        if max_start < 1:
            result.append(0.0)
            continue
        # Sample a few windows and average
        n_windows = min(20, max_start)
        starts = np.linspace(0, max_start, n_windows, dtype=int)
        d3_vals = []
        for s in starts:
            end = min(N, s + int(L) + 1)
            if end - s < 3:
                continue
            x = np.arange(s, end + 1, dtype=float)
            y = cumulative[s:end + 1]
            # Linear fit
            try:
                p = np.polyfit(x, y, 1)
                fit = np.polyval(p, x)
                residual = y - fit
                d3 = np.mean(residual ** 2)
                d3_vals.append(d3)
            except Exception:
                continue
        result.append(float(np.mean(d3_vals)) if d3_vals else 0.0)
    return np.array(result)


def sigma2_curve(unfolded: np.ndarray, L_grid: np.ndarray) -> np.ndarray:
    """Number variance Σ²(L)."""
    if len(unfolded) < 5:
        return np.zeros_like(L_grid)
    N = len(unfolded)
    cumulative = np.concatenate([[0], np.cumsum(unfolded)])
    result = []
    for L in L_grid:
        L = float(L)
        if L < 1:
            result.append(0.0)
            continue
        max_start = max(0, N - int(L) - 1)
        if max_start < 1:
            result.append(0.0)
            continue
        n_windows = min(50, max_start)
        starts = np.linspace(0, max_start, n_windows, dtype=int)
        counts = []
        for s in starts:
            end = min(N, s + int(L) + 1)
            n_in_window = cumulative[end] - cumulative[s]
            counts.append(n_in_window)
        counts = np.array(counts, dtype=float)
        if len(counts) > 0:
            var = float(np.var(counts))
        else:
            var = 0.0
        result.append(var)
    return np.array(result)


def sigma2_gue_theory(L: float) -> float:
    """GUE Σ²(L) = (2/π²)·[ln(2πL) + γ - Si(2πL) + cos(2πL)·... ] (approximation)."""
    if L <= 0:
        return 0.0
    x = 2 * math.pi * L
    # Asymptotic
    return (2.0 / math.pi**2) * (math.log(2 * math.pi * L) + 0.5772156649 - math.pi / 2)


def delta3_gue_theory(L: float) -> float:
    """GUE Δ₃(L) = (1/π²)·[ln(2πL) + γ - 3/4] (asymptotic)."""
    if L <= 0:
        return 0.0
    return (1.0 / math.pi**2) * (math.log(2 * math.pi * L) + 0.5772156649 - 0.75)


