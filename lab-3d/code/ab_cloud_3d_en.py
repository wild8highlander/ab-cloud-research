def plot_3d_exceptional_points(cfg: SimConfig, run_dir: Path) -> None:
    run_dir = Path(run_dir)
    alphas = np.linspace(0, 0.5, 15)
    sigmas = np.linspace(0, 1.0, 15)
    A, S = np.meshgrid(alphas, sigmas)
    min_dE = np.zeros_like(A)
    for i in range(len(sigmas)):
        for j in range(len(alphas)):
            cfg2 = SimConfig(Lx=4, Ly=4, Lz=2, tz=cfg.tz, sigma=float(sigmas[i]),
                             alpha=float(alphas[j]), disorder=0.0, bc_z=cfg.bc_z,
                             nev=cfg.nev, n_zeros=cfg.n_zeros, poly_deg=cfg.poly_deg,
                             fs_L_max=cfg.fs_L_max, arf_levels=cfg.arf_levels, out_dir=cfg.out_dir)
            try:
                sim = run_3d_simulation(cfg2)
                ev = sim["evals"]
                # Min |dE| (closest pair coalescence)
                if len(ev) > 1:
                    re = np.sort(ev.real)
                    d = np.diff(re)
                    min_dE[i, j] = float(np.min(d[d > 1e-9])) if np.any(d > 1e-9) else 0.0
            except Exception:
                min_dE[i, j] = float('nan')
    fig = plt.figure(figsize=(10, 7))
    ax = fig.add_subplot(111, projection='3d')
    ax.plot_surface(A, S, min_dE, cmap='plasma')
    ax.set_xlabel('α')
    ax.set_ylabel('σ')
    ax.set_zlabel('min |dE|')
    ax.set_title('Exceptional points landscape')
    fig.tight_layout()
    fig.savefig(run_dir / "3d_exceptional_points.png", dpi=120)
    plt.close(fig)


