def build_hamiltonian_3d(cfg: SimConfig) -> np.ndarray:
    """Build the AB-Cloud 3D non-Hermitian topological Hamiltonian.

    Lattice: Lx×Ly×Lz, with sublattices A/B in the xy-plane (checkerboard).
    Nearest-neighbor in-plane hopping has Peierls phase exp(±i·α·π) per plaquette.
    Interlayer hopping tz with optional σ non-Hermiticity (gain/loss).
    """
    Lx, Ly, Lz = cfg.Lx, cfg.Ly, cfg.Lz
    N = Lx * Ly * Lz * 2  # ×2 for A/B sublattice
    H = np.zeros((N, N), dtype=complex)

    def idx(x, y, z, sub):
        # sub: 0=A, 1=B
        return ((z * Ly + y) * Lx + x) * 2 + sub

    alpha = cfg.alpha
    tz = cfg.tz
    sigma = cfg.sigma
    bc_z = cfg.bc_z

    for z in range(Lz):
        for y in range(Ly):
            for x in range(Lx):
                # Sublattice A at (x,y,z), connects to B at (x+1,y), (x,y+1), (x,y,z±1)
                iA = idx(x, y, z, 0)
                # In-plane NN: A(x,y) -> B(x+1,y) and A(x,y) -> B(x,y+1)
                # with AB phase ±α·π/2 (depending on sublattice pattern)
                # Use checkerboard: A at even (x+y+z), B at odd
                # phase = ±i * α * π  (sigma_xx = ±α)
                phase_x = 1.0 if (y % 2 == 0) else -1.0
                phase_y = 1.0 if (x % 2 == 0) else -1.0
                # A -> B(x+1, y)
                if x + 1 < Lx:
                    iB = idx(x + 1, y, z, 1)
                    H[iA, iB] += 1.0 + 1j * alpha * phase_x
                    H[iB, iA] += 1.0 - 1j * alpha * phase_x
                # A -> B(x, y+1)
                if y + 1 < Ly:
                    iB = idx(x, y + 1, z, 1)
                    H[iA, iB] += 1.0 + 1j * alpha * phase_y
                    H[iB, iA] += 1.0 - 1j * alpha * phase_y
                # Interlayer A(z) -> A(z+1) and B(z) -> B(z+1)
                if z + 1 < Lz:
                    iA2 = idx(x, y, z + 1, 0)
                    H[iA, iA2] += tz * (1 + 1j * sigma)
                    H[iA2, iA] += tz * (1 - 1j * sigma)
                    iB = idx(x, y, z, 1)
                    iB2 = idx(x, y, z + 1, 1)
                    H[iB, iB2] += tz * (1 + 1j * sigma)
                    H[iB2, iB] += tz * (1 - 1j * sigma)
                elif bc_z == "PBC" and Lz > 1:
                    iA2 = idx(x, y, 0, 0)
                    H[iA, iA2] += tz * (1 + 1j * sigma)
                    H[iA2, iA] += tz * (1 - 1j * sigma)
                    iB = idx(x, y, z, 1)
                    iB2 = idx(x, y, 0, 1)
                    H[iB, iB2] += tz * (1 + 1j * sigma)
                    H[iB2, iB] += tz * (1 - 1j * sigma)
                # On-site: A gain +σ, B loss -σ (if non-Hermitian)
                if sigma != 0:
                    iB = idx(x, y, z, 1)
                    H[iA, iA] += 1j * sigma * 0.5
                    H[iB, iB] -= 1j * sigma * 0.5
                # Disorder (diagonal)
                if cfg.disorder > 0:
                    rng = np.random.default_rng(x * Ly * Lz + y * Lz + z)
                    H[iA, iA] += cfg.disorder * (rng.random() - 0.5) * 2
                    H[iB, iB] += cfg.disorder * (rng.random() - 0.5) * 2
    return H


def run_3d_simulation(cfg: SimConfig) -> Dict[str, Any]:
    """Build H, diagonalize, return eigenvalues + observables."""
    H = build_hamiltonian_3d(cfg)
    evals = eigvals(H)
    # Sort by real part
    evals_sorted = evals[np.argsort(evals.real)]
    real_E = evals_sorted.real
    # Spacings
    sp = np.diff(real_E)
    sp = sp[sp > 1e-6]
    if len(sp) > 0:
        ns = sp / sp.mean()
    else:
        ns = np.array([])
    # ⟨r⟩ ratio
    if len(ns) > 1:
        r_vals = np.minimum(ns[:-1], ns[1:]) / np.maximum(ns[:-1], ns[1:])
        mean_r = float(r_vals.mean())
    else:
        mean_r = 0.0
    # Wavefunction density at band center
    eivals, eivecs = eig(H)
    mid = len(eivals) // 2
    psi_mid = eivecs[:, mid]
    density = np.abs(psi_mid) ** 2
    return {
        "H": H,
        "evals": evals,
        "evals_sorted": evals_sorted,
        "real_E": real_E,
        "norm_spacings": ns,
        "mean_r": mean_r,
        "z_density": density,
        "N": H.shape[0],
    }


