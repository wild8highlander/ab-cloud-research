def wigner_dyson_pdf(s: float) -> float:
    if s <= 0:
        return 0.0
    return (math.pi / 2) * s * math.exp(-(math.pi / 4) * s * s)


def poisson_pdf(s: float) -> float:
    if s <= 0:
        return 0.0
    return math.exp(-s)


def gue_pair_correlation(x: float) -> float:
    if x <= 0:
        return 0.0
    return 1.0 - (math.sin(math.pi * x) / (math.pi * x)) ** 2


def gue_form_factor(tau: float) -> float:
    if tau <= 0:
        return 0.0
    if tau < 1:
        return 2.0 * tau - tau * math.log(1.0 + tau)
    return 2.0 - tau * math.log((tau + 1) / (tau - 1)) if tau > 1 else 0.0


def compute_S_T(zeros: List[float]) -> List[float]:
    """S(T) = (1/π)·arg(ζ(1/2 + iT)) — fluctuation of the zeta phase."""
    result = []
    _mp.mp.dps = 25
    for T in zeros:
        try:
            s_T = float(_mp.im(_mp.log(_mp.zeta(_mp.mpc(0.5, T)))) / _mp.pi)
            result.append(s_T)
        except Exception:
            result.append(0.0)
    return result


