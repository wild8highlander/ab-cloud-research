def run_mode_zeta_rmt(cfg: SimConfig) -> None:
    """[B] RMT analysis of embedded zeta zeros."""
    print("\n>>> Mode: RMT analysis of zeta zeros (KS, ⟨r⟩, Δ₃, Σ²)")
    run_dir, ts = make_run_dir(cfg, "zeta_RMT")
    z = load_embedded_zeros(cfg.n_zeros)
    n = len(z)
    unfolded = unfold_zeta_zeros(z)
    sp = np.diff(unfolded)
    sp = sp[sp > 1e-6]
    ns = sp / sp.mean()
    r_vals = np.array([min(ns[i], ns[i+1]) / max(ns[i], ns[i+1])
                       for i in range(len(ns)-1)
                       if ns[i] > 1e-6 and ns[i+1] > 1e-6])
    mean_r = float(r_vals.mean()) if len(r_vals) > 0 else 0.0
    D_g, p_g = ks_statistic(ns, gue_cdf)
    D_p, p_p = ks_statistic(ns, poisson_cdf)
    L_grid = np.arange(2, cfg.fs_L_max + 1, 2, dtype=float)
    d3 = delta_3_curve(unfolded, L_grid)
    s2 = sigma2_curve(unfolded, L_grid)
    d3_t = np.array([delta3_gue_theory(L) for L in L_grid])
    s2_t = np.array([sigma2_gue_theory(L) for L in L_grid])
    report = {
        "mode": "B_RMT_zeta",
        "n_zeros_requested": cfg.n_zeros,
        "n_zeros_used": n,
        "first_zero": float(z[0]),
        "last_zero": float(z[-1]),
        "mean_r": mean_r,
        "GUE_mean_r_theory": 0.6027,
        "Poisson_mean_r_theory": 0.3863,
        "KS_vs_GUE_D": D_g, "KS_vs_GUE_p": p_g,
        "KS_vs_Poisson_D": D_p, "KS_vs_Poisson_p": p_p,
        "delta3_max": float(np.nanmax(d3)) if len(d3) > 0 else 0.0,
        "sigma2_max": float(np.nanmax(s2)) if len(s2) > 0 else 0.0,
        "verdict": "GUE-chaos (Riemann zeros ARE GUE-distributed)" if mean_r > 0.55 else "ambiguous",
    }
    write_all_reports(report, run_dir, "report_rmt")
    plot_rmt_results(unfolded, ns, mean_r, run_dir, L_grid, d3, d3_t, s2, s2_t)
    print(f"\n[RMT] Done. Folder: {run_dir}")
    print(f"      n_zeros={n}, ⟨r⟩={mean_r:.4f} (GUE≈0.6027), KS D={D_g:.4f}")


