def write_all_reports(report: Dict[str, Any], run_dir: Path, prefix: str = "verification") -> None:
    """Write report dict to JSON, TXT, MD formats."""
    run_dir = Path(run_dir)
    # JSON
    with open(run_dir / f"{prefix}.json", "w", encoding="utf-8") as f:
        json.dump(_json_sanitize(report), f, indent=2, ensure_ascii=False)
    # TXT (key = value lines)
    with open(run_dir / f"{prefix}.txt", "w", encoding="utf-8") as f:
        _write_dict_txt(f, report, prefix)
    # MD
    with open(run_dir / f"{prefix}.md", "w", encoding="utf-8") as f:
        f.write(f"# {prefix}\n\n")
        _write_dict_md(f, report, depth=0)


def _json_sanitize(obj: Any) -> Any:
    """Make object JSON-serializable: convert numpy types, Path, complex, etc."""
    if isinstance(obj, dict):
        return {k: _json_sanitize(v) for k, v in obj.items()}
    if isinstance(obj, (list, tuple)):
        return [_json_sanitize(x) for x in obj]
    if isinstance(obj, (np.integer,)):
        return int(obj)
    if isinstance(obj, (np.floating,)):
        v = float(obj)
        if math.isfinite(v):
            return v
        return None
    if isinstance(obj, (np.bool_,)):
        return bool(obj)
    if isinstance(obj, np.ndarray):
        return [_json_sanitize(x) for x in obj.tolist()]
    if isinstance(obj, complex):
        return {"real": obj.real, "imag": obj.imag}
    if isinstance(obj, Path):
        return str(obj)
    if isinstance(obj, float):
        if not math.isfinite(obj):
            return None
        return obj
    return obj


def _write_dict_txt(f, obj: Any, prefix: str = "", depth: int = 0) -> None:
    if isinstance(obj, dict):
        for k, v in obj.items():
            if isinstance(v, (dict, list)):
                f.write(f"{'  ' * depth}{k}:\n")
                _write_dict_txt(f, v, prefix, depth + 1)
            else:
                f.write(f"{'  ' * depth}{k} = {_fmt_value(v)}\n")
    elif isinstance(obj, list):
        for i, v in enumerate(obj):
            if isinstance(v, (dict, list)):
                f.write(f"{'  ' * depth}[{i}]:\n")
                _write_dict_txt(f, v, prefix, depth + 1)
            else:
                f.write(f"{'  ' * depth}[{i}] = {_fmt_value(v)}\n")


def _write_dict_md(f, obj: Any, depth: int = 0) -> None:
    if isinstance(obj, dict):
        for k, v in obj.items():
            if isinstance(v, dict):
                f.write(f"\n{'#' * (depth + 2)} {k}\n\n")
                _write_dict_md(f, v, depth + 1)
            elif isinstance(v, list):
                f.write(f"\n{'#' * (depth + 2)} {k}\n\n")
                for i, item in enumerate(v):
                    if isinstance(item, dict):
                        f.write(f"\n**Item {i}:**\n\n")
                        for kk, vv in item.items():
                            f.write(f"- {kk}: {_fmt_value(vv)}\n")
                    else:
                        f.write(f"- {_fmt_value(item)}\n")
            else:
                f.write(f"- **{k}**: {_fmt_value(v)}\n")


def _fmt_value(v: Any) -> str:
    if isinstance(v, float):
        if math.isnan(v):
            return "NaN"
        if math.isinf(v):
            return "Inf" if v > 0 else "-Inf"
        return f"{v:.6g}"
    if isinstance(v, complex):
        return f"{v.real:.6g}{v.imag:+.6g}i"
    return str(v)


