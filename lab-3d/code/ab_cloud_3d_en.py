def parse_float_unlimited(prompt: str) -> float:
    """Parse a Float64 from stdin. Accepts inf/+inf/∞/-inf/-∞/nan/infinity
    and any finite float. Re-prompts on invalid input."""
    while True:
        try:
            s = input(prompt).strip()
            if s == "":
                return float('nan')  # signal "leave unchanged"
            sl = s.lower()
            if sl in ("inf", "+inf", "∞", "infinity", "+∞"):
                return float('inf')
            if sl in ("-inf", "-∞", "-infinity"):
                return float('-inf')
            if sl in ("nan", "n/a"):
                return float('nan')
            return float(s)
        except ValueError:
            print(f"[!] Could not parse '{s}' as a number. Please try again (or inf/-inf/∞/nan).")


def parse_int_unlimited(prompt: str) -> int:
    """Parse an Int from stdin. 'inf'/'max' → 2^31-1, 'min' → -2^31.
    Re-prompts on invalid input."""
    while True:
        try:
            s = input(prompt).strip()
            if s == "":
                return 0  # signal "leave unchanged"
            sl = s.lower()
            if sl in ("inf", "max", "+inf", "∞", "+∞", "infinity"):
                return 2**31 - 1
            if sl in ("-inf", "min", "-∞", "-infinity"):
                return -(2**31)
            return int(s)
        except ValueError:
            print(f"[!] Could not parse '{s}' as integer. Please try again (or inf/max/min).")


def parse_int3_unlimited(prompt: str) -> Optional[Tuple[int, int, int]]:
    """Parse three space-separated integers. Each accepts inf/max/min."""
    while True:
        try:
            s = input(prompt).strip()
            if s == "":
                return None
            tokens = s.split()
            if len(tokens) != 3:
                print(f"[!] Expected 3 values, got {len(tokens)}. Please try again.")
                continue
            result = []
            for tok in tokens:
                tl = tok.lower()
                if tl in ("inf", "max", "+inf", "∞", "+∞", "infinity"):
                    result.append(2**31 - 1)
                elif tl in ("-inf", "min", "-∞", "-infinity"):
                    result.append(-(2**31))
                else:
                    result.append(int(tok))
            return (result[0], result[1], result[2])
        except ValueError:
            print(f"[!] Could not parse '{s}'. Please try again.")


