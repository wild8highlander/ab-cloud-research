def riemann_siegel_theta(t: float) -> float:
    """θ(t) = Im(log Γ(1/4 + i t/2)) − (t/2)·log(π)."""
    if t <= 0:
        return 0.0
    _mp.mp.dps = 25  # 25 decimal places — sufficient for ~1e-15 accuracy
    z = _mp.mpc(_mp.mpf(0.25), _mp.mpf(t) / 2)
    return float(_mp.im(_mp.loggamma(z)) - (t / 2) * _mp.log(_mp.pi))


def riemann_siegel_Z(t: float) -> float:
    """Hardy Z(t) = exp(i·θ(t))·ζ(1/2 + i t). Real on the critical line.

    Uses mpmath at 25 dps for machine-precision accuracy. This is the
    'perfect accuracy' version requested by the user.
    """
    if t <= 0:
        return -1.0 if t == 0 else 0.0
    _mp.mp.dps = 25
    # mpmath.siegelz computes Re(exp(i*theta) * zeta(0.5+it)) directly
    return float(_mp.siegelz(t))


def _riemann_siegel_Z_fast(t: float) -> float:
    """Faster Hardy Z using lower precision (15 dps). Used only for the
    initial sign-change scan; final bisection uses full precision.
    """
    if t <= 0:
        return -1.0 if t == 0 else 0.0
    _mp.mp.dps = 15
    return float(_mp.siegelz(t))


def nth_riemann_zero(n: int) -> float:
    """Return the imaginary part of the n-th nontrivial Riemann zeta zero.

    Perfect accuracy: For n > 30, uses sequential sign-change detection on
    Hardy Z(t) (via mpmath). Each zero is found to ~1e-12 precision via
    bisection. Cache is maintained so subsequent calls are fast.

    Cost: ~5–20 ms per zero (mpmath evaluation is the bottleneck).
    For n=100, total ~1 sec; for n=1000, ~15 sec; for n=5500, ~90 sec.
    """
    if n <= 0:
        return float('nan')
    if n <= len(_HARDCODED_30_ZEROS):
        return _HARDCODED_30_ZEROS[n - 1]
    if n in _RIEMANN_ZERO_CACHE:
        return _RIEMANN_ZERO_CACHE[n]

    # Sequential search: iterate from n=31 upward
    t_prev = _HARDCODED_30_ZEROS[-1]
    for k in range(len(_HARDCODED_30_ZEROS) + 1, n + 1):
        if k in _RIEMANN_ZERO_CACHE:
            t_prev = _RIEMANN_ZERO_CACHE[k]
            continue
        # Average zero spacing at height t_prev: ~ 2π/ln(t_prev/2π)
        spacing = 2.0 * math.pi / max(math.log(t_prev / (2.0 * math.pi)), 1.0)
        t_lo = t_prev + 0.2 * spacing
        t_hi = t_prev + 4.0 * spacing
        # Dense sign-change scan — use lower precision for speed
        n_scan = 80
        ts = np.linspace(t_lo, t_hi, n_scan)
        fs = np.array([_riemann_siegel_Z_fast(float(tv)) for tv in ts])
        found = float('nan')
        for i in range(n_scan - 1):
            if fs[i] * fs[i + 1] < 0:
                # Bisection refinement — use full precision for the final answer
                a, b = float(ts[i]), float(ts[i + 1])
                fa, fb = float(fs[i]), float(fs[i + 1])
                for _ in range(60):  # 60 iterations gives ~1e-18 precision
                    m = 0.5 * (a + b)
                    fm = riemann_siegel_Z(m)
                    if abs(fm) < 1e-14 or abs(b - a) < 1e-14:
                        a = b = m
                        break
                    if fa * fm < 0:
                        b, fb = m, fm
                    else:
                        a, fa = m, fm
                found = 0.5 * (a + b)
                break
        if math.isnan(found):
            # Fallback: asymptotic estimate (Lambert-W)
            target = float(k) - 11.0 / 8.0
            t_approx = 2.0 * math.pi * target / max(math.log(target), 1.0)
            print(f"  [WARN] no sign change for k={k}; using asymptotic {t_approx}")
            found = t_approx
        _RIEMANN_ZERO_CACHE[k] = found
        t_prev = found
    return _RIEMANN_ZERO_CACHE[n]


def load_embedded_zeros(n_requested: Optional[int] = None) -> List[float]:
    """Return the first `n_requested` Riemann zeta zeros.

    - n is None: return all 5000 embedded zeros.
    - n <= 5000: return embedded[0:n].
    - n > 5000: return embedded + (n - 5000) generated via nth_riemann_zero
                (perfect accuracy via mpmath).
    - n is huge (> 10^7, treated as Inf): cap at 5000 + 1000 = 6000.
    """
    embedded = list(_EMBEDDED_ZEROS)
    if n_requested is None:
        return embedded
    if n_requested >= 2**31 - 1 or n_requested > 10**7:  # inf / max
        print(f"[load_embedded_zeros] n_requested={n_requested} huge; capping at 6000")
        n_requested = len(embedded) + 1000
    if n_requested <= len(embedded):
        return embedded[:n_requested]
    # Need to generate n_requested - 5000 extra zeros
    extra = []
    for k in range(len(embedded) + 1, n_requested + 1):
        extra.append(nth_riemann_zero(k))
    return embedded + extra


