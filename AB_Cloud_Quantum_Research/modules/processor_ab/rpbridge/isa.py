# -*- coding: utf-8 -*-
"""rpbridge.isa — V20: система команд (ISA) AB-облака.

Физическая база — полный гамильтониан AB-облака в форме V18
(эффективный двухуровневый блок решётки: масса m, туннель t, фаза φ
из флакса). Кампания V18 доказала точность шести фиксированных ворот
{X, Y, Z, H, S, T} (fidelity 1−2e-16). Кампания V20 снимает фиксацию
УГЛОВ: фазовое пространство AB-облака континуально (фаза = функционал
глобальной флакс-конфигурации), поэтому ISA дополняется тремя
параметрическими примитивами, каждый из которых калибруется
АНАЛИТИЧЕСКИ на блочном гамильтониане:

  AB2(a, b; θ, λ, φ) — двухуровневый блок-импульс: произвольная SU(2)
      на паре вычислительных базисных состояний |a⟩, |b⟩ (резонансный
      калиброванный импульс перехода; обобщение механизма P1 V18 с
      соседних сайтов на произвольную пару).
  ABPH(S; φ) — топологический фазовый затвор: уровень состояния, в
      котором все кубиты подсистемы S в |1⟩, сдвинут детюнингом Δ;
      эволюция t = φ/Δ даёт точную контролируемую фазу e^{iφ}
      (механизм V18-P2: «детюнинг к |↑↑⟩» — взаимодействие без поля
      на партнёре).
  RX(θ), RZ(φ) — частные случаи AB2 (одно-кубитные импульсы туннеля
      и массы).

Все примитивы исполняются ТОЧНО (матричная алгебра, машинный пол) —
это спецификация процессора; вопрос физического носителя вынесен в
честные границы (results/ROADMAP.md, P-фазы).

ISA = {AB2, ABPH} + производные {RX, RZ, CPHASE, CNOT, H, X, Z, S, T}.
Универсальность: двухуровневые блоки порождают U(2^n) в точности
(Nielsen–Chuang, теорема о two-level унитарных), ABPH замыкает
диагональную фазу — компилятор (compiler.py) строит ТОЧНЫЕ схемы.
"""
import numpy as np
from scipy.linalg import expm

# ── блочный гамильтониан AB (V18, P1) ───────────────────────────────────────
M_MASS = 2.0
T_HOP = 1.0


def block_hamiltonian(m=M_MASS, t=T_HOP, phi=np.pi / 2):
    """Эффективный 2×2 блок: H = m·σz − t(cos φ·σx + sin φ·σy)."""
    return np.array([[m, -t * np.exp(-1j * phi)],
                     [-t * np.exp(1j * phi), -m]], dtype=np.complex128)


# ── примитивы ISA ───────────────────────────────────────────────────────────
def rz(phi):
    """AB(φ)-фазовый затвор RZ(φ) = diag(1, e^{iφ}).

    Фаза φ = 2π·Φ/Φ0 — голономия вокруг вихря (континуум флакса).
    SU(2)-часть: exp(−i(φ/2)σz) с точностью до глобальной фазы.
    """
    return np.diag([1.0, np.exp(1j * phi)]).astype(np.complex128)


def rx(theta):
    """Туннельный импульс RX(θ) = exp(−i(θ/2)σx) (m = 0, t·t_pulse = θ/2)."""
    c, s = np.cos(theta / 2), np.sin(theta / 2)
    return np.array([[c, -1j * s], [-1j * s, c]], dtype=np.complex128)


def ab2(theta, lam, phi):
    """Произвольный двухуровневый блок-импульс (ZXZ-калибровка Эйлера):

    AB2(θ, λ, φ) = RZ(φ)·RX(θ)·RZ(λ) — универсальная SU(2) (3 угла).
    Физика: резонансный импульс перехода |a⟩↔|b⟩ (обобщение P1 V18).
    """
    return rz(phi) @ rx(theta) @ rz(lam)


def abph_level(n, x, phi):
    """Фазовый затвор уровня PHASE(x; φ): фаза e^{iφ} на базисном
    уровне |x⟩ (селективный детюнинг Δ·|x⟩⟨x|, эволюция t = φ/Δ —
    механизм V18-P2, обобщённый с уровня |11⟩ на произвольный уровень;
    в AB-облаке уровни — состояния вихревой конфигурации, и фаза есть
    функционал глобального флакса — многочастичный характер фазы
    согласован с законом V19 ζ^{ra+sb}).
    """
    D = np.ones(1 << n, dtype=np.complex128)
    if x > 0:
        D[x] = np.exp(1j * phi)
    return np.diag(D)


def cphase(phi):
    """CPHASE(φ) = PHASE(0b11; φ) — контролируемая AB-фаза на паре."""
    return np.diag([1.0, 1.0, 1.0, np.exp(1j * phi)]).astype(np.complex128)


def cnot():
    """CNOT = H₂·CPHASE(π)·H₂ (производный затвор)."""
    h = np.array([[1, 1], [1, -1]], dtype=np.complex128) / np.sqrt(2)
    return np.kron(np.eye(2, dtype=np.complex128), h) @ cphase(np.pi) @ \
        np.kron(np.eye(2, dtype=np.complex128), h)


# фиксированные ворота V18 — частные случаи (таблица ISA)
FIXED = {
    'X': rx(np.pi) @ rz(0.0),
    'Z': rz(np.pi),
    'S': rz(np.pi / 2),
    'T': rz(np.pi / 4),
}
H_GATE = ab2(np.pi / 2, 0.0, np.pi) * np.exp(-1j * np.pi / 4)  # до фазы


# ── применение затворов к регистру (n кубитов, dense) ──────────────────────
def embed_1q(n, q, g):
    """Встраивание одно-кубитного затвора g на кубит q (крон-порядок:
    индекс = Σ bit_q·2^q; q = 0 — младший)."""
    ops = [np.eye(2, dtype=np.complex128)] * n
    ops[n - 1 - q] = g
    out = ops[0]
    for o in ops[1:]:
        out = np.kron(out, o)
    return out


def embed_2q(n, qa, qb, g):
    """Встраивание двухкубитного затвора g (4×4, крон-конвенция:
    первый фактор — кубит qa, индекс g = 2·bit_qa + bit_qb) на кубиты
    qa и qb в n-кубитный регистр (битовая арифметика)."""
    dim = 1 << n
    U = np.zeros((dim, dim), dtype=np.complex128)
    mask = (1 << qa) | (1 << qb)
    for x in range(dim):
        a = (x >> qa) & 1          # входной бит qa
        b = (x >> qb) & 1          # входной бит qb
        rest = x & ~mask
        for i2 in range(2):        # выходной бит qa
            for j2 in range(2):    # выходной бит qb
                w = g[i2 * 2 + j2, a * 2 + b]
                if w != 0:
                    y = rest | (i2 << qa) | (j2 << qb)
                    U[y, x] += w
    return U


def embed_abph_level(n, x, phi):
    return abph_level(n, x, phi)


# ── калибровка импульсов (продолжение V18: аналитика + экспонента) ─────────
def pulse_calibration():
    """Проверка аналитической калибровки трёх примитивов на блочном
    гамильтониане: fidelity F = |Tr(U_t† U)|²/d (глобальная фаза не
    влияет). Порог спецификации: ≥ 1 − 1e-15 на каждый примитив."""
    def fid(U, V, d):
        return float(abs(np.trace(U.conj().T @ V)) ** 2 / (d * d))

    out = {}
    # RX(θ): чистый туннель m=0, t=1: H = −σx → exp(−iHt) = exp(iσx t);
    # RX(θ) = exp(−iθσx/2): t_pulse = θ/2 (знак фазы — калибровка φ=π)
    H = block_hamiltonian(m=0.0, t=1.0, phi=0.0)
    U = expm(-1j * H * (np.pi / 2))
    out['RX'] = dict(fidelity=fid(U, rx(np.pi), 2), t_pulse=np.pi / 2)
    # RZ(φ): чистая масса m=2: H = 2σz → exp(−iHt) = diag(e^{−2imt}...);
    # e^{+iφ} на |1⟩: t_pulse = φ/(2m) с φ = π даёт t = π/4 (модуль фазы)
    H = block_hamiltonian(m=M_MASS, t=0.0)
    U = expm(-1j * H * (np.pi / (4 * M_MASS)))
    out['RZ'] = dict(fidelity=fid(U, rz(np.pi / 2), 2),
                     t_pulse=np.pi / (4 * M_MASS))
    # ABPH/PHASE: детюнинг уровня |11⟩ на Δ: H = Δ·|11⟩⟨11| →
    # exp(−iHt) = CPHASE(Δt) (механизм P2 V18)
    Delta = 3.0
    Hc = np.diag([0, 0, 0, Delta]).astype(np.complex128)
    U = expm(-1j * Hc * (np.pi / Delta))
    out['PHASE'] = dict(fidelity=fid(U, cphase(np.pi), 4),
                        t_pulse=np.pi / Delta, detuning=Delta)
    return out


